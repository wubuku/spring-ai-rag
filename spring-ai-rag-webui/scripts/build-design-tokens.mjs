#!/usr/bin/env node
/**
 * Deterministic design token generator.
 *
 * Reads the canonical source `design-tokens/tokens.json` and emits tracked,
 * reproducible outputs:
 *
 *   src/styles/tokens.css            -> `:root` (light) + `[data-theme="dark"]`
 *   src/design-system/tokens.generated.ts -> TS bridge for libraries that need
 *                                            real colour values (Recharts) and
 *                                            CSS var() references
 *
 * Rules enforced here (see docs/drafts/WEBUI_UNIFIED_DESIGN_LANGUAGE_PLAN.md §8):
 *   - themed groups must define `light` and `dark` for every token (symmetry);
 *   - non-themed groups must define a single `value`;
 *   - CSS custom property names are unique and kebab-case;
 *   - aliases may only point at canonical tokens, never at other aliases,
 *     which makes alias cycles structurally impossible.
 *
 * Output never embeds a timestamp: running `tokens:build` twice must not
 * produce a diff.
 */

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { isMainModule } from './lib/is-main-module.mjs';

const projectRoot = fileURLToPath(new URL('..', import.meta.url));

export const SOURCE_PATH = join(projectRoot, 'design-tokens/tokens.json');
export const CSS_OUTPUT_PATH = join(projectRoot, 'src/styles/tokens.css');
export const TS_OUTPUT_PATH = join(projectRoot, 'src/design-system/tokens.generated.ts');

const GENERATED_BANNER = [
  '/* Generated by scripts/build-design-tokens.mjs from design-tokens/tokens.json.',
  ' * Do not edit by hand: run `npm run tokens:build`.',
  ' */',
].join('\n');

const TS_BANNER = [
  '/**',
  ' * Generated by scripts/build-design-tokens.mjs from design-tokens/tokens.json.',
  ' * Do not edit by hand: run `npm run tokens:build`.',
  ' *',
  ' * This bridge exposes token *names* and `var()` references only. Libraries',
  ' * such as Recharts need concrete values, so they resolve the final themed',
  ' * value at runtime with `resolveTokenValues()` instead of duplicating a',
  ' * second copy of the palette in TypeScript.',
  ' */',
].join('\n');

const CSS_VAR_NAME = /^--[a-z0-9]+(?:-[a-z0-9]+)*$/;
const HEX_COLOR = /^#(?:[0-9a-f]{3,4}|[0-9a-f]{6}|[0-9a-f]{8})$/i;
const FUNCTIONAL_COLOR = /^(?:rgba?|hsla?)\(.+\)$/i;

function isThemedColor(value) {
  return HEX_COLOR.test(value) || FUNCTIONAL_COLOR.test(value);
}

/**
 * Themed values must be non-empty; colour-valued groups additionally reject
 * anything that is not a colour literal, so an arbitrary literal cannot be
 * smuggled into the palette. Themed non-colour groups (e.g. shadow) stay
 * theme-symmetric without being forced into a colour shape.
 */
function validateThemedValue(value, label, valueKind, errors) {
  if (typeof value !== 'string' || value.trim() === '') {
    errors.push(`${label} must be a non-empty string`);
    return;
  }
  if (valueKind === 'color' && !isThemedColor(value)) {
    errors.push(
      `${label} must be a colour literal (hex, rgb()/rgba(), hsl()/hsla()); got "${value}"`,
    );
  }
}

function validateScalarValue(value, label, errors) {
  if (typeof value !== 'string' || value.trim() === '') {
    errors.push(`${label} must be a non-empty string`);
  }
}

/**
 * Parse and validate the canonical source.
 * @param {string} text raw JSON text
 * @returns {{version: number, groups: Array, aliases: Array, cssVarToToken: Map<string, object>}}
 */
export function parseSource(text) {
  const errors = [];
  let raw;
  try {
    raw = JSON.parse(text);
  } catch (error) {
    throw new Error(`design-tokens/tokens.json is not valid JSON: ${error.message}`);
  }

  if (!raw || typeof raw !== 'object') throw new Error('token source must be a JSON object');
  if (!Array.isArray(raw.groups) || raw.groups.length === 0) {
    throw new Error('token source must declare a non-empty "groups" array');
  }

  const aliases = Array.isArray(raw.aliases) ? raw.aliases : [];
  const cssVarToToken = new Set();
  const seenGroupNames = new Set();
  // The TypeScript bridge exposes group-qualified keys (`color-bg`, `space-4`),
  // because bare token keys legitimately repeat across groups — `4` exists in
  // both `space` and `radius`. Track them so a collision is a build error rather
  // than a silently overwritten object property.
  const bridgeKeys = new Set();

  const claimVarName = (name, label) => {
    if (typeof name !== 'string' || !CSS_VAR_NAME.test(name)) {
      errors.push(`${label} var name "${name}" must match --kebab-case`);
      return;
    }
    if (cssVarToToken.has(name)) {
      errors.push(`${label} reuses CSS custom property ${name} (already declared)`);
      return;
    }
    cssVarToToken.add(name);
  };

  const claimBridgeKey = (bridgeKey, label) => {
    if (bridgeKeys.has(bridgeKey)) {
      errors.push(
        `${label} produces duplicate TypeScript bridge key "${bridgeKey}". ` +
          'Rename the token key or qualify it with its group.',
      );
      return;
    }
    bridgeKeys.add(bridgeKey);
  };

  const groups = raw.groups.map((group, groupIndex) => {
    const groupName = group?.name;
    if (typeof groupName !== 'string' || groupName.trim() === '') {
      errors.push(`groups[${groupIndex}] is missing a name`);
    } else if (seenGroupNames.has(groupName)) {
      errors.push(`duplicate group name "${groupName}"`);
    } else {
      seenGroupNames.add(groupName);
    }

    const themed = group?.themed === true;
    const valueKind = group?.valueKind === 'scalar' ? 'scalar' : 'color';
    if (group?.tokens !== undefined && !Array.isArray(group.tokens)) {
      errors.push(`group "${groupName}" tokens must be an array`);
    }

    const tokens = (Array.isArray(group?.tokens) ? group.tokens : []).map((token, tokenIndex) => {
      const label = `group "${groupName}" token #${tokenIndex}`;
      if (typeof token?.key !== 'string' || token.key.trim() === '') {
        errors.push(`${label} is missing a key`);
      }
      claimVarName(token?.var, `${label} (${token?.key ?? tokenIndex})`);

      if (themed) {
        if ('value' in token) {
          errors.push(`${label} is in a themed group and must not declare a single "value"`);
        }
        validateThemedValue(token?.light, `${label} (${token?.key}) light`, valueKind, errors);
        validateThemedValue(token?.dark, `${label} (${token?.key}) dark`, valueKind, errors);
      } else {
        if ('light' in token || 'dark' in token) {
          errors.push(`${label} is in a non-themed group and must not declare light/dark`);
        }
        validateScalarValue(token?.value, `${label} (${token?.key}) value`, errors);
      }
      claimBridgeKey(`${groupName}-${token?.key}`, label);
      return { ...token, themed, bridgeKey: `${groupName}-${token?.key}` };
    });

    return {
      name: groupName,
      description: typeof group?.description === 'string' ? group.description : '',
      themed,
      valueKind,
      tokens,
    };
  });

  const canonicalVars = new Set();
  for (const group of groups) {
    for (const token of group.tokens) {
      if (CSS_VAR_NAME.test(String(token.var))) canonicalVars.add(token.var);
    }
  }

  const aliasKeys = new Set();
  const parsedAliases = aliases.map((alias, aliasIndex) => {
    const label = `aliases[${aliasIndex}]`;
    if (typeof alias?.key !== 'string' || alias.key.trim() === '') {
      errors.push(`${label} is missing a key`);
    } else if (aliasKeys.has(alias.key)) {
      errors.push(`duplicate alias key "${alias.key}"`);
    } else {
      aliasKeys.add(alias.key);
    }
    claimVarName(alias?.var, `${label} (${alias?.key ?? aliasIndex})`);

    const ref = alias?.ref;
    if (typeof ref !== 'string' || !CSS_VAR_NAME.test(ref)) {
      errors.push(`${label} (${alias?.key}) ref "${ref}" must be a canonical token name`);
    } else if (!canonicalVars.has(ref)) {
      // Aliases may not point at aliases; this is what makes cycles impossible.
      errors.push(
        `${label} (${alias?.key}) ref ${ref} is not a canonical token. ` +
          'Aliases must reference a token var, not another alias.',
      );
    }
    return { key: alias?.key, var: alias?.var, ref };
  });

  if (errors.length > 0) {
    throw new Error(`Invalid design token source:\n  - ${errors.join('\n  - ')}`);
  }

  return { version: Number(raw.version ?? 1), groups, aliases: parsedAliases, cssVarToToken };
}

/**
 * Declaration lines for one selector. Themed groups emit their light or dark
 * value; non-themed groups are theme-independent and are therefore emitted only
 * once, in `:root`, so the dark block stays a minimal delta.
 */
function declarationsFor(groups, { theme, includeStatic }) {
  const lines = [];
  for (const group of groups) {
    if (group.themed) {
      for (const token of group.tokens) {
        lines.push(`  ${token.var}: ${token[theme]};`);
      }
    } else if (includeStatic) {
      for (const token of group.tokens) {
        lines.push(`  ${token.var}: ${token.value};`);
      }
    }
  }
  return lines;
}

/** Render the generated stylesheet. Light is the default; dark overrides only themed tokens. */
export function renderCss(model) {
  const parts = [GENERATED_BANNER, ''];
  parts.push(':root {');
  parts.push('  color-scheme: light;');
  parts.push(...declarationsFor(model.groups, { theme: 'light', includeStatic: true }));
  if (model.aliases.length > 0) {
    parts.push('');
    parts.push('  /* Compatibility aliases: only allowed to shrink, never to grow. */');
    for (const alias of model.aliases) {
      parts.push(`  ${alias.var}: var(${alias.ref});`);
    }
  }
  parts.push('}');
  parts.push('');
  parts.push('[data-theme="dark"] {');
  parts.push('  color-scheme: dark;');
  parts.push(...declarationsFor(model.groups, { theme: 'dark', includeStatic: false }));
  parts.push('}');
  parts.push('');
  return parts.join('\n');
}

function toCamelCase(key) {
  return key.replace(/-([a-z0-9])/g, (_, char) => char.toUpperCase());
}

/** Render the TypeScript bridge: names + var() references, never palette copies. */
export function renderTs(model) {
  const lines = [TS_BANNER, ''];
  lines.push('/** Group-qualified token names, e.g. `color-bg`, `space-4`, `chart-axis`. */');
  lines.push('export const DESIGN_TOKEN_VARS = {');
  for (const group of model.groups) {
    for (const token of group.tokens) {
      lines.push(`  '${token.bridgeKey}': '${token.var}',`);
    }
  }
  lines.push('} as const;');
  lines.push('');
  lines.push('export type DesignTokenKey = keyof typeof DESIGN_TOKEN_VARS;');
  lines.push('');
  lines.push('export const CHART_TOKEN_VARS = {');
  const chartGroup = model.groups.find(group => group.name === 'chart');
  for (const token of chartGroup?.tokens ?? []) {
    lines.push(`  '${token.bridgeKey}': '${token.var}',`);
  }
  lines.push('} as const;');
  lines.push('');
  lines.push('export type ChartTokenKey = keyof typeof CHART_TOKEN_VARS;');
  lines.push('');
  lines.push('/** Reference a token without hard-coding its CSS name at the call site. */');
  lines.push('export function cssVarRef(key: DesignTokenKey): string {');
  lines.push('  return `var(${DESIGN_TOKEN_VARS[key]})`;');
  lines.push('}');
  lines.push('');
  lines.push('/**');
  lines.push(' * Read the *resolved* value of each requested token from the live theme.');
  lines.push(' * Use this for SVG presentation attributes and chart libraries, which');
  lines.push(' * cannot consume var() references.');
  lines.push(' *');
  lines.push(' * Keys are type-checked against the token source, so a typo or a removed');
  lines.push(' * token is a compile error rather than a silently empty colour.');
  lines.push(' */');
  lines.push('export function resolveTokenValues(');
  lines.push('  keys: readonly DesignTokenKey[],');
  lines.push('): Readonly<Record<string, string>> {');
  lines.push('  const style = getComputedStyle(document.documentElement);');
  lines.push('  const result: Record<string, string> = {};');
  lines.push('  for (const key of keys) {');
  lines.push('    result[key] = style.getPropertyValue(DESIGN_TOKEN_VARS[key]).trim();');
  lines.push('  }');
  lines.push('  return result;');
  lines.push('}');
  lines.push('');
  return lines.join('\n');
}

export function buildOutputs(text) {
  const model = parseSource(text);
  return {
    model,
    css: renderCss(model),
    ts: renderTs(model),
    outputs: [
      { path: CSS_OUTPUT_PATH, content: renderCss(model) },
      { path: TS_OUTPUT_PATH, content: renderTs(model) },
    ],
  };
}

function main() {
  const check = process.argv.includes('--check');
  const { outputs } = buildOutputs(readFileSync(SOURCE_PATH, 'utf8'));
  const stale = [];

  for (const { path, content } of outputs) {
    if (check) {
      let current = null;
      try {
        current = readFileSync(path, 'utf8');
      } catch {
        current = null;
      }
      if (current !== content) {
        stale.push(path);
      }
    } else {
      mkdirSync(dirname(path), { recursive: true });
      writeFileSync(path, content);
      console.log(`wrote ${path.replace(`${projectRoot}`, '.')}`);
    }
  }

  if (check) {
    if (stale.length > 0) {
      console.error('Generated design tokens are out of date:');
      for (const path of stale) console.error(`- ${path.replace(`${projectRoot}`, '.')}`);
      console.error('Run `npm run tokens:build` and commit the result.');
      process.exitCode = 1;
      return;
    }
    console.log('Design tokens are in sync with design-tokens/tokens.json');
  }
}

if (isMainModule(import.meta.url)) {
  try {
    main();
  } catch (error) {
    console.error(error.message);
    process.exitCode = 1;
  }
}
