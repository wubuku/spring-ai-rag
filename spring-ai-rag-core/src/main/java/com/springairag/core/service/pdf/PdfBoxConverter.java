package com.springairag.core.service.pdf;

import com.springairag.core.properties.RagPdfProperties;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.stereotype.Component;
import org.springframework.beans.factory.annotation.Autowired;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;

/**
 * PDF to Markdown converter using Apache PDFBox.
 *
 * <p>This is a pure Java implementation with no external dependencies. It can only
 * extract text and cannot preserve layout or images.
 *
 * <p>Output: {@code {outputDir}/{pdfName}/{pdfName}.md}
 */
@Component
public class PdfBoxConverter implements PdfConverter {

    private static final Logger log = LoggerFactory.getLogger(PdfBoxConverter.class);
    private final RagPdfProperties pdfProperties;

    public PdfBoxConverter() {
        this(new RagPdfProperties());
    }

    @Autowired
    public PdfBoxConverter(RagPdfProperties pdfProperties) {
        this.pdfProperties = pdfProperties;
    }

    @Override
    public boolean convert(Path pdfPath, Path outputDir) {
        if (pdfPath == null) {
            log.error("pdfPath must not be null");
            return false;
        }
        if (outputDir == null) {
            log.error("outputDir must not be null");
            return false;
        }
        if (!Files.isRegularFile(pdfPath)) {
            log.error("PDF file does not exist: {}", pdfPath);
            return false;
        }
        String pdfName = pdfPath.getFileName().toString();
        // Strip .pdf suffix
        if (pdfName.toLowerCase().endsWith(".pdf")) {
            pdfName = pdfName.substring(0, pdfName.length() - 4);
        }

        // Create output subdirectory
        Path outputSubDir = outputDir.resolve(pdfName);
        Path outputMdFile = outputSubDir.resolve(pdfName + ".md");

        try {
            Files.createDirectories(outputSubDir);

            // 抽取器负责加密、损坏、无文字层与页数预算；失败原因原样上抛，
            // 由 PdfImportService 映射为 4xx，而不是落到通用 500。
            String text = PdfTextExtractor.extractText(pdfPath, pdfProperties.getMaxPages());

            // Build Markdown
            String markdown = buildMarkdown(pdfName, text);
            if (markdown.getBytes(StandardCharsets.UTF_8).length
                    > pdfProperties.getMaxInMemoryBytes()) {
                throw new PdfConversionException(
                        PdfConversionException.Reason.OUTPUT_TOO_LARGE,
                        "PDFBox output exceeds max in-memory bytes");
            }

            // Write Markdown file
            Files.writeString(outputMdFile, markdown, StandardCharsets.UTF_8);

            log.info("PDFBox extracted text to: {}", outputMdFile);
            return true;

        } catch (IOException e) {
            log.error("PDFBox conversion failed for {}: {}", pdfPath, e.getMessage());
            throw new PdfConversionException(
                    PdfConversionException.Reason.INVALID_PDF,
                    "PDF conversion failed", e);
        }
    }

    @Override
    public boolean isAvailable() {
        // PDFBox is always available (provided by Spring Boot starter dependency)
        return true;
    }

    @Override
    public String getName() {
        return "Apache PDFBox (text only)";
    }

    private String buildMarkdown(String title, String extractedText) {
        StringBuilder md = new StringBuilder();

        // Title
        md.append("# ").append(title).append("\n\n");
        md.append("*Extracted from PDF automatically. Layout may not be preserved.*\n\n");
        md.append("## Content\n\n");

        // Split by double newlines (paragraphs)
        String[] paragraphs = extractedText.split("\n\\s*\n");
        for (String para : paragraphs) {
            String trimmed = para.trim();
            if (trimmed.isEmpty()) continue;
            if (trimmed.contains("\n") || trimmed.length() > 80) {
                md.append(trimmed.replaceAll("\\n", "  \n")).append("\n\n");
            } else {
                md.append(trimmed).append("\n\n");
            }
        }

        md.append("\n---\n");
        md.append("*Generated by spring-ai-rag PDF Import (PDFBox)*\n");

        return md.toString();
    }
}
